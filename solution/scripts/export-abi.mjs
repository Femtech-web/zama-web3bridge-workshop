import { readFile, writeFile, mkdir } from "node:fs/promises";
import { format, resolveConfig } from "prettier";

const out = new URL("../frontend/lib/contracts/", import.meta.url);
const formatting = await resolveConfig(new URL("../.prettierrc.json", import.meta.url));
await mkdir(out, { recursive: true });
for (const [contractFile, name, exportName] of [
  ["ConfidentialPayroll.sol", "ConfidentialPayroll", "payrollAbi"],
  ["WorkshopAssets.sol", "ConfidentialWorkshopUSD", "wrapperAbi"],
]) {
  const artifact = JSON.parse(
    await readFile(
      new URL(`../artifacts/contracts/${contractFile}/${name}.json`, import.meta.url),
      "utf8",
    ),
  );
  const source = `// Generated by npm run compile; do not edit.\nexport const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  await writeFile(
    new URL(`${exportName}.ts`, out),
    await format(source, { ...formatting, parser: "typescript" }),
  );
}
